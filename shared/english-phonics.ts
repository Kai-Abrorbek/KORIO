/**
 * An introductory, accent-aware US English reading guide, shared by both clients.
 * Explanations are authored for Korio; source links are references, not copied lessons.
 * IPA describes whole words. Speech synthesis must receive `word`, never IPA.
 */
export type PhonicsLocale = "ko" | "en" | "uz" | "ru";
export type LocalizedText = Record<PhonicsLocale, string>;

export interface PhonicsExample {
  word: string;
  ipa: string;
  /** Zero-based, half-open spelling ranges, not positions in the IPA. */
  focus: readonly (readonly [number, number])[];
  meaning: LocalizedText;
}

export interface PhonicsRule {
  id: string;
  pattern: string;
  sound: string;
  title: LocalizedText;
  explanation: LocalizedText;
  examples: readonly PhonicsExample[];
  caution?: LocalizedText;
}

export interface PhonicsCheck {
  prompt: LocalizedText;
  options: readonly [PhonicsExample, PhonicsExample];
  correctIndex: 0 | 1;
  explanation: LocalizedText;
}

export interface EnglishPhonicsGuide {
  letter: string;
  name: string;
  nameIpa: string;
  koreanName: string;
  tip: LocalizedText;
  rules: readonly PhonicsRule[];
  contrast?: {
    title: LocalizedText;
    explanation: LocalizedText;
    examples: readonly [PhonicsExample, PhonicsExample];
  };
  check: PhonicsCheck;
}

export function phonicsText(value: LocalizedText, locale: string): string {
  const base = locale.toLowerCase().replace(/_/g, "-").split("-")[0];
  return base === "ko" || base === "uz" || base === "ru"
    ? value[base]
    : value.en;
}

export function phonicsSegments(
  example: PhonicsExample,
): { text: string; highlighted: boolean }[] {
  const result: { text: string; highlighted: boolean }[] = [];
  let cursor = 0;
  // Do not duplicate or lose letters if a future content edit supplies bad ranges.
  const ranges = [...example.focus].sort((a, b) => a[0] - b[0]);
  for (const [rawStart, rawEnd] of ranges) {
    const start = Math.max(cursor, Math.min(example.word.length, rawStart));
    const end = Math.max(start, Math.min(example.word.length, rawEnd));
    if (start > cursor)
      result.push({
        text: example.word.slice(cursor, start),
        highlighted: false,
      });
    if (end > start)
      result.push({ text: example.word.slice(start, end), highlighted: true });
    cursor = end;
  }
  if (cursor < example.word.length)
    result.push({ text: example.word.slice(cursor), highlighted: false });
  return result;
}

