export function getEnglishPhonics(
  letter: string,
): EnglishPhonicsGuide | undefined {
  const input = letter.trim();
  const match = /^(?:en-)?([a-z])$/i.exec(input) ?? /^([a-z])\1$/i.exec(input);
  const key = match?.[1]?.toUpperCase();
  return key
    ? ENGLISH_PHONICS.find((guide) => guide.letter === key)
    : undefined;
}

