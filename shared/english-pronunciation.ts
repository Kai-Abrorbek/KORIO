const P = (word: string, jamo: string): PronOption => ({ word, jamo });
const stage = (
  step: number,
  a: string,
  b: string,
  pos: PronStage["pos"],
  leftBubble: string,
  leftWord: string,
  rightBubble: string,
  rightWord: string,
  words: [string, string][],
): PronStage => ({
  step,
  a: `/${a}/`,
  b: `/${b}/`,
  pos,
  leftBubble,
  leftWord,
  rightBubble,
  rightWord,
  pairs: words.map(([left, right]) => [P(left, a), P(right, b)]),
});

