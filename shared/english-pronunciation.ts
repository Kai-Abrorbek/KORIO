export function englishPronunciationGloss(
  word: string,
  locale: string,
): string {
  const language = locale.trim().toLowerCase().split(/[-_]/)[0];
  const key: Locale =
    language === "ko" || language === "uz" || language === "ru"
      ? language
      : "en";
  return (
    ENGLISH_PRON_GLOSSES[word]?.[key] ?? ENGLISH_PRON_GLOSSES[word]?.en ?? ""
  );
}

