/**
 * 소리로 읽을 글을 다듬는다 — 자막은 그대로 두고 **읽을 글만** 손본다.
 *
 * api/src/tutor/tts/for-speaking.ts 를 옮겨 온 것이다 (예전 TTS 튜터에서
 * 실제로 겪고 고친 규칙들). Agent 는 API 코드를 못 불러오는 별도 배포라서
 * 복사했다. 규칙을 고치면 **양쪽을 같이** 고쳐라.
 *
 * 왜: 따옴표·괄호·줄임표는 눈으로 읽는 기호다. 음성 엔진은 그 자리에서 길게
 * 쉬거나(1초 넘게) 기호를 읽으려 든다. 튜터가 예문을 자주 인용해서 대화
 * 내내 "말하다가 뚝 멈췄다 이어지는" 느낌이 났다.
 *
 * 이 파일에서 더한 것:
 *  - ㅋㅋ·ㅎㅎ·ㅠㅠ — 한글 자모라 한국어 구간으로 잘려서 "크크" 로 읽힌다
 *  - **굵게** 같은 마크다운 강조 기호
 */
export function forSpeech(text: string): string {
  return (
    text
      // 우즈벡어 o' g' 는 글자다 (ko'rsatadi). 앞뒤가 라틴 글자인 아포스트로피는 남긴다.
      // 한국어 옆에 붙은 따옴표('단어')는 라틴 글자가 아니니 지워진다.
      .replace(/['\u{2018}\u{2019}\u{02BB}\u{02BC}]/gu, (m, i: number) =>
        /[A-Za-z]/.test(text[i - 1] ?? '') && /[A-Za-z]/.test(text[i + 1] ?? '') ? m : '',
      )
      .replace(/["\u{201C}\u{201D}\u{201E}\u{300C}\u{300D}\u{300E}\u{300F}\u{00AB}\u{00BB}]/gu, '')
      // 괄호 안 보충설명은 소리로 들으면 문맥이 끊긴다. 쉼표로 눕힌다
      .replace(/[\u{FF08}(]\s*/gu, ', ')
      .replace(/\s*[\u{FF09})]/gu, '')
      .replace(/[[\]{}<>]/g, '')
      // 마크다운 강조
      .replace(/(\*\*|__|\*|`)/g, '')
      // 웃음·울음 자모 — 소리로 못 낸다
      .replace(/[ㅋㅎ]{2,}|[ㅠㅜ]{2,}/g, '')
      // 줄임표·대시는 긴 침묵이 된다
      .replace(/[.]{2,}|\u{2026}/gu, ',')
      .replace(/\s*[\u{2014}\u{2013}~]+\s*/gu, ', ')
      // 목록 기호·이모지 (모델이 가끔 붙인다)
      .replace(/^[\s*\-\u{2022}\d]+[.)]\s*/gmu, '')
      .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, '')
      // 위 치환이 만든 겹친 문장부호와 공백을 정리한다
      .replace(/,\s*,+/g, ',')
      .replace(/\s*,\s*([.?!])/g, '$1')
      .replace(/[ \t]{2,}/g, ' ')
      .replace(/^[\s,]+/, '')
      .trim()
  );
}
