/**
 * 소리로 읽을 문장을 다듬는다.
 *
 * 화면에 보이는 자막은 그대로 두고 **읽을 텍스트만** 손본다.
 *
 * 왜: 따옴표·괄호·줄임표는 눈으로 읽으라고 있는 기호다. 음성 엔진은 그 자리에서
 * 길게 쉬거나(때로는 1초 넘게) 기호 자체를 읽으려 든다. 튜터가 예문을 자주
 * 인용하기 때문에 이게 대화 내내 튀었다 — "말하다가 뚝 멈췄다 이어지는" 느낌의
 * 정체가 이것이다.
 *
 * 프롬프트로도 "따옴표 쓰지 마라" 고 했지만 모델은 가끔 쓴다. 마지막 방어선을
 * 소리 나가기 직전에 둔다.
 *
 * 서비스에서 떼어낸 이유: 순수 함수인데 서비스 파일에 있으면 테스트하려고
 * NestJS 를 통째로 로드해야 한다. 판정 규칙이 까다로워서(아래 아포스트로피)
 * 테스트가 꼭 필요하다.
 */
export function forSpeaking(text: string): string {
  return (
    text
      // 인용부호는 지운다. 인용은 억양으로 하는 것이지 기호로 하는 게 아니다.
      //
      // ⚠️ 낱말 **안**의 아포스트로피는 남긴다. 우즈벡어에서 o' 와 g' 는 따로
      //    있는 글자다 — ko'rsatadi 에서 이걸 지우면 korsatadi 가 되어 다른
      //    말이 된다. 튜터가 우즈벡어로도 답하게 되면서 생긴 문제다.
      //    앞뒤가 모두 라틴 글자면 글자로 보고 건드리지 않는다. 한국어 옆에
      //    붙은 따옴표('단어')는 라틴 글자가 아니므로 그대로 지워진다.
      .replace(
        /['\u2018\u2019\u02bb\u02bc]/g,
        (m, i: number) =>
          /[A-Za-z]/.test(text[i - 1] ?? '') && /[A-Za-z]/.test(text[i + 1] ?? '')
            ? m
            : '',
      )
      .replace(/["\u201c\u201d\u300c\u300d\u300e\u300f\u00ab\u00bb]/g, '')
      // 괄호 안 보충설명은 소리로 들으면 문맥이 끊긴다. 쉼표로 눕힌다
      .replace(/[（(]\s*/g, ', ')
      .replace(/\s*[）)]/g, '')
      .replace(/[[\]{}<>]/g, '')
      // 줄임표·대시는 긴 침묵이 된다
      .replace(/[.]{2,}|\u2026/g, ',')
      .replace(/\s*[\u2014\u2013~]+\s*/g, ', ')
      // 목록 기호·이모지 (모델이 가끔 붙인다)
      .replace(/^[\s*\-\u2022\d]+[.)]\s*/gm, '')
      .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, '')
      // 위 치환이 만든 겹친 문장부호와 공백을 정리한다
      .replace(/,\s*,+/g, ',')
      .replace(/\s*,\s*([.?!])/g, '$1')
      .replace(/\s{2,}/g, ' ')
      .replace(/^[\s,]+/, '')
      .trim()
  );
}
