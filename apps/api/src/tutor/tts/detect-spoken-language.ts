import type { TutorTtsLanguage } from './tutor-tts.types';

/**
 * 튜터가 뱉은 문장 하나를 어느 목소리로 읽을 것인가.
 *
 * 왜 필요한가: 목소리는 언어별로 다른 음성이다. 우즈벡어 문장을 한국어 음성
 * (ko-KR-*)에 넣으면 라틴 문자를 한국어 규칙으로 읽어서 알아들을 수 없는 소리가
 * 난다. 목소리를 외부 TTS 로 옮긴 이유가 "한국어가 외국인 억양처럼 들려서"
 * 였는데, 그 반대를 하는 셈이 된다.
 *
 * 왜 앱이 아니라 서버인가: 판정 기준이 두 군데 있으면 반드시 갈라진다. 그리고
 * 앱이 보내는 language 를 그대로 믿으면, 틀린 힌트 하나가 응답 전체를 엉뚱한
 * 목소리로 읽게 만든다. 텍스트는 어차피 서버로 오므로 여기서 정한다.
 *
 * **글자 수가 많은 쪽이 이긴다.** "한글이 있으면 한국어" 같은 단순 규칙으로는
 * 안 되는 이유:
 *
 *   아메리카노는 kofe 예요                     → 한글이 많다  → 한국어 ✓
 *   -러 가다 biror joyga borishni bildiradi   → 라틴이 많다  → 우즈벡어 ✓
 *
 * 둘째 줄을 "한글이 하나라도 있으면 한국어" 로 판정하면 우즈벡어 설명 전체를
 * 한국어 음성이 읽는다. 프롬프트가 우즈벡어 설명에 한국어 예문을 붙이도록
 * 유도하기 때문에 이 경우가 자주 나온다.
 *
 * 소수쪽 글자가 조금 이상하게 읽히는 건 감수한다 — 문장의 대부분이 제대로
 * 들리는 쪽이 언제나 낫다. 프롬프트에서도 한 문장 안에 두 언어를 섞지 말라고
 * 따로 못 박는다.
 */

/** 한글 음절 + 자모 */
const HANGUL = /[가-힣ㄱ-ㆎ]/g;
/** 라틴 글자 (우즈벡어는 라틴 표기) */
const LATIN = /[A-Za-z]/g;

export function detectSpokenLanguage(text: string): TutorTtsLanguage {
  if (!text) return 'ko';
  const hangul = text.match(HANGUL)?.length ?? 0;
  const latin = text.match(LATIN)?.length ?? 0;

  // 라틴 글자가 없으면 볼 것도 없다 (숫자·부호만 있는 조각 포함)
  if (latin === 0) return 'ko';
  if (hangul === 0) return 'uz';

  /**
   * 섞였을 때는 한국어에 유리하게 센다.
   *
   * 한글 한 글자는 음절 하나라 라틴 2~3글자에 해당한다. 글자 수를 그대로
   * 비교하면 "아메리카노는 kofe 예요" 같은 정상적인 한국어 문장이 우즈벡어로
   * 넘어간다. 학습 앱이라 애매하면 한국어 쪽이 맞다.
   */
  return hangul * 2 >= latin ? 'ko' : 'uz';
}
