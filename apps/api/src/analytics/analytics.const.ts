/**
 * 계측의 한계값.
 *
 * 앱이 보내는 값이라 전부 상한을 건다. 분석 데이터라 학습을 막지는 않지만,
 * 오염되면 어드민의 모든 숫자가 같이 틀어진다.
 */

/** 한 번의 보고에 받는 최대 답안 수 */
export const MAX_ANSWERS_PER_REPORT = 60;

/** 한 판에서 인정하는 최대 문제 번호 (본풀이 + 복습 라운드) */
export const MAX_QUESTION_INDEX = 200;

/** 문제 하나에 인정하는 최대 풀이 시간 (10분). 앱이 백그라운드로 갔다 오면 값이 튄다 */
export const MAX_QUESTION_DURATION_MS = 10 * 60 * 1000;

/**
 * 이 시간이 지나도 완료 신호가 안 오면 이탈로 본다.
 *
 * 상태를 나중에 cron 으로 바꾸지 않고 **읽을 때 판단한다** — 앱이 죽거나
 * 비행기 모드가 되면 "끝냈다" 신호가 영영 안 오는데, 그걸 기다리는 cron 은
 * 결국 같은 추측을 나중에 하는 것뿐이다.
 */
export const ABANDON_AFTER_MS = 2 * 60 * 60 * 1000;
