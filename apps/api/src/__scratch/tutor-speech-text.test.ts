/**
 * 소리로 읽을 문장 다듬기.
 *
 * 따옴표·괄호·줄임표가 남아 있으면 음성 엔진이 그 자리에서 길게 쉰다.
 * 튜터가 예문을 자주 인용해서 대화 내내 "말하다 뚝 멈추는" 느낌이 났다.
 *
 * 실행: npx ts-node src/__scratch/tutor-speech-text.test.ts
 */
import { forSpeaking } from '../tutor/tutor-speech.service';

let fail = 0;
const say = (ok: boolean, msg: string) => {
  if (!ok) fail++;
  console.log(`${ok ? '✅' : '❌'} ${msg}`);
};
const eq = (input: string, want: string, msg: string) => {
  const got = forSpeaking(input);
  say(got === want, `${msg}\n     "${input}"\n   → "${got}"`);
};

// ── 인용부호 (제일 흔한 원인) ──────────────────────────────────
eq(
  '아, 그건 한국어로 \'액션 영화를 봤어요\' 예요.',
  '아, 그건 한국어로 액션 영화를 봤어요 예요.',
  '작은따옴표 제거',
);
eq('"안녕하세요" 라고 해요.', '안녕하세요 라고 해요.', '큰따옴표 제거');
eq('“커피 주세요”라고 하면 돼요.', '커피 주세요라고 하면 돼요.', '한글 인용부호도');

// ── 긴 침묵을 만드는 것들 ─────────────────────────────────────
eq('음... 그러니까요.', '음, 그러니까요.', '줄임표는 쉼표로');
eq('음… 맞아요.', '음, 맞아요.', '한 글자 줄임표도');
eq('그건 — 조금 어려워요.', '그건, 조금 어려워요.', '대시는 쉼표로');
eq('아메리카노(뜨거운 거) 주세요.', '아메리카노, 뜨거운 거 주세요.', '괄호는 쉼표로 눕힌다');

// ── 눈으로만 읽는 것들 ────────────────────────────────────────
eq('좋아요 😊 다시 해볼까요?', '좋아요 다시 해볼까요?', '이모지 제거');
eq('1. 안녕하세요\n2. 반갑습니다', '안녕하세요\n반갑습니다', '목록 번호 제거');

// ── 치운 뒤 지저분해지지 않아야 한다 ──────────────────────────
eq('그래서... , 갔어요.', '그래서, 갔어요.', '겹친 쉼표를 합친다');
eq('정말요...?', '정말요?', '쉼표가 문장부호 앞에 남지 않는다');
eq('  ...그래요.', '그래요.', '앞머리 기호와 공백을 턴다');

// ── 건드리면 안 되는 것 ───────────────────────────────────────
eq('오늘 뭐 했어요?', '오늘 뭐 했어요?', '멀쩡한 문장은 그대로');
eq('가격은 3.5 달러예요.', '가격은 3.5 달러예요.', '소수점은 줄임표가 아니다');
eq('네! 좋아요.', '네! 좋아요.', '느낌표는 살린다');
say(forSpeaking('') === '', '빈 문자열도 안전');
say(forSpeaking('"""') === '', '기호만 있으면 빈 결과 (호출부가 걸러낸다)');

// 한국어 글자를 잃지 않는다
{
  const src = '어제 친구랑 "영화관"에 갔어요... 재밌었어요!';
  const out = forSpeaking(src);
  const keep = (v: string) => v.replace(/[^가-힣]/g, '');
  say(keep(out) === keep(src), '한글은 한 글자도 안 잃는다');
}

console.log(fail ? `\n❌ ${fail}건 실패` : '\n🎉 전부 통과');
process.exit(fail ? 1 : 0);
