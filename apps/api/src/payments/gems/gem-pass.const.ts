/**
 * 보석으로 사는 프리미엄 기간권.
 *
 * **왜 "할인" 이 아니라 "기간" 인가.**
 * 구글 플레이 구독 가격은 Play Console 에 등록된 고정 SKU 다. "이 유저한테는
 * 5,000 so'm 빼고 받아줘" 같은 API 가 없고, 줄어든 금액을 스토어 밖에서 받으면
 * 외부 결제 유도라 계정이 정지된다 (claude/결제-시스템.md 참고).
 * 그래서 결제를 건드리지 않고, 인앱 통화로 인앱 컨텐츠(프리미엄 기간)를 판다.
 * 유저 체감은 같고 — 보석이 돈이 된다 — 규칙 위반이 없다.
 *
 * **1 보석 = 1 so'm** 이 기준이다. 기간이 길수록 하루 단가가 싸진다.
 *
 *   3일   5,000   1,667/일   기준
 *   7일  10,000   1,429/일   -14%
 *  14일  18,000   1,286/일   -23%
 *  30일  33,000   1,100/일   -34%
 *
 * 보석을 어디서 모으나 (이 가격이 말이 되는지의 근거):
 *   친구 초대   1명당 1,000 + 마일스톤(3명 1,000 · 10명 3,000 · 25명 8,000 · 50명 20,000)
 *   학습        노드 상자 평균 17 → 하루 4~5개면 70~85
 *   리그 상자   주 20~200 (1~3위)
 *
 * → 25명 초대 = 37,000 ≈ 30일권 하나. 초대가 압도적으로 큰 경로이고
 *   그게 의도다. 체감이 짜면 상자 보석을 올리는 쪽이 먼저다 (이 표보다).
 */
export interface GemPass {
  /** 앱·서버가 같이 쓰는 식별자 */
  id: string;
  days: number;
  gems: number;
}

export const GEM_PASSES: GemPass[] = [
  { id: 'days_3', days: 3, gems: 5000 },
  { id: 'days_7', days: 7, gems: 10000 },
  { id: 'days_14', days: 14, gems: 18000 },
  { id: 'days_30', days: 30, gems: 33000 },
];

export const gemPassById = (id: string): GemPass | undefined =>
  GEM_PASSES.find((pass) => pass.id === id);

/**
 * 보석 기간권으로 쌓을 수 있는 프리미엄의 상한(일).
 *
 * 없으면 보석 부자가 몇 년치를 한 번에 쌓아두고 영영 결제하지 않는다.
 * 남은 기간이 이 값을 넘으면 더 못 산다 — 막는 게 아니라 "나중에 또 오라" 는
 * 장치다.
 */
export const GEM_PASS_MAX_STACK_DAYS = 60;
