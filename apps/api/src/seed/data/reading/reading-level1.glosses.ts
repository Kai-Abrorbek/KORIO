export function getLevel1ReadingGloss(word: string, english: string) {
  const key = `${word}\t${english}`;
  const gloss = LEVEL1_READING_GLOSSES[key];
  if (!gloss) {
    throw new Error(`1급 읽기 어휘의 현지어 뜻이 없습니다: ${word} (${english})`);
  }
  return { uz: gloss[0], ru: gloss[1] };
}
