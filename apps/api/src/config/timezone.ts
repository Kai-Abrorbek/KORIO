// 서버 프로세스의 로컬 시간대를 UTC 로 고정한다.
//
// 예전에는 Asia/Seoul 이었다. 그때는 하루·한 주의 경계를 곳곳에서
// `new Date(); setHours(0,0,0,0)` 로 잡았고, 그게 곧 KST 자정이었다.
// 유저는 우즈베키스탄(UTC+5)에도 한국에도 있어서, 타슈켄트 유저가 저녁 8시
// 이후에 공부하면 그 기록이 다음 날로 넘어갔다.
//
// 이제 경계는 전부 `common/date.util.ts` 가 **명시적인 시간대**로 계산한다
// (유저 기록은 그 유저의 tz, 리그는 LEAGUE_TIMEZONE). 그래서 이 값은 원칙적으로
// 아무 데도 영향을 주면 안 된다.
//
// 그래도 APP_TIMEZONE 과 같은 값으로 둔다. 아직 서버 로컬 getter(getMonth 등)를
// 쓰는 표시용 코드가 조금 남아 있는데, UTC 로 두면 그것들이 모든 유저에게
// 어긋나고 이 값으로 두면 최소한 다수(우즈베키스탄)에게는 맞는다.
// 새 코드에서 서버 로컬 시간에 기대지 마라 — date.util 을 써라.
//
// 반드시 다른 어떤 모듈보다 먼저 import 되어야 한다 (main.ts 최상단).
process.env.TZ = 'Asia/Tashkent';
