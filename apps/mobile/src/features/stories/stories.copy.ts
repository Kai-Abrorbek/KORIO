export type StoriesCopy = (typeof COPY)["en"];

export function useStoriesCopy(): StoriesCopy {
  const language = useSettingsStore((state) => state.language);
  const base = (language ?? "uz").toLowerCase().split(/[-_]/)[0];
  return COPY[base as keyof typeof COPY] ?? COPY.uz;
}

/** 설명 언어 코드를 독 버튼에 짧게 (UZ · RU · 한) */
export function translationBadge(lang: string): string {
  if (lang === "ko") return "한";
  return lang.toUpperCase().slice(0, 2);
}

/** 46160 → "0:46" */
export function formatClock(ms: number): string {
  const total = Math.max(0, Math.round(ms / 1000));
  const minutes = Math.floor(total / 60);
  const seconds = total % 60;
  return `${minutes}:${seconds.toString().padStart(2, "0")}`;
}
